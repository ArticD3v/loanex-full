export function findCreditReview(applicationId: string): CreditReview | undefined {
  return MOCK_CREDIT_REVIEWS.find((item) => item.applicationId === applicationId);
}

export function updateCreditReviewDecision(
  applicationId: string,
  patch: Partial<CreditReview>,
): CreditReview | undefined {
  const review = findCreditReview(applicationId);
  if (!review) return undefined;
  Object.assign(review, patch);
  return review;
}
